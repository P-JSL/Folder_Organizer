"""Disposable native-Windows contracts for the new frozen multi-root CLI paths.

This module does not run programs on import. It compares both release programs
with generated byte truth and retained file metadata, rather than trusting that
two matching reports must necessarily be correct.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import subprocess
from typing import Any


VERSION = "0.8.0"
SCHEMA = "folder-organizer.multiroot.v1"
MIB = 1024 * 1024


def file_receipt(path: Path) -> dict[str, Any]:
    with path.open("rb") as stream:
        sha256 = hashlib.file_digest(stream, "sha256").hexdigest()
    return {"file": path.name, "bytes": path.stat().st_size, "sha256": sha256}


def _ordinary(path: str | Path) -> str:
    absolute = Path(os.path.abspath(os.fspath(path)))
    # The runner TEMP environment can contain a DOS 8.3 parent (RUNNER~1),
    # while the application reports the same directory's canonical long name.
    # Resolve the parent, including the existing prefix of an offline path,
    # but retain the final file name: hardlink aliases are distinct inventory
    # paths and must not be collapsed through an opened file handle.
    value = str(absolute.parent.resolve(strict=False) / absolute.name)
    if os.name == "nt":
        value = value.replace("/", "\\")
    if os.name == "nt":
        if value.startswith("\\\\?\\UNC\\"):
            value = "\\\\" + value[8:]
        elif value.startswith("\\\\?\\"):
            value = value[4:]
        value = os.path.normcase(value)
    return os.path.normpath(value)


@dataclass
class Fixture:
    base: Path
    left: Path
    right: Path
    nested: Path
    session: Path
    roots: list[Path]
    # Every fixture file, including excluded storage, is retained for invariance.
    originals: dict[str, dict[str, Any]]
    # The regular paths which are eligible before explicit size filtering.
    eligible: list[Path]


def create_fixture(parent: Path) -> Fixture:
    """Generate a small Unicode/overlap/hardlink fixture under a fresh child."""
    base = parent / "fixture-input"
    base.mkdir(parents=True, exist_ok=False)
    left, right = base / "a-작업", base / "b-보관"
    nested = left / "nested-자료"
    nested.mkdir(parents=True)
    right.mkdir()
    block = hashlib.sha256(b"v080 frozen multi-root content").digest()
    large = block * (4 * MIB // len(block))
    first, second, copy = left / "first.dat", nested / "second.dat", right / "copy.dat"
    for path in (first, second, copy):
        path.write_bytes(large)
    different = right / "different.dat"
    different.write_bytes(b"X" * len(large))
    alias = right / "link-alias.dat"
    os.link(first, alias)
    if not os.path.samefile(first, alias) or first.stat().st_ino == 0:
        raise RuntimeError("The native release fixture requires stable hardlink identity")
    small, small_copy = left / "메모.txt", right / "메모 사본.txt"
    for path in (small, small_copy):
        path.write_bytes(b"new release read-only scope\n" * 101)
    subtitle = left / "한국어 자막.smi"
    subtitle.write_bytes("<SAMI><BODY><SYNC Start=0><P>가나다 자막</P></BODY></SAMI>".encode("cp949"))
    session = base / "session-이름비교"
    session.mkdir()
    for number in range(3):
        (session / f"shared-document-{number}.txt").write_bytes(bytes([65 + number]) * 512)
    (left / "ignored.skip").write_bytes(large)
    for folder, name in (("delete_files", "held.dat"), (".folder-organizer", "history.json"),
                         ("#recycle", "server.dat")):
        destination = left / folder
        destination.mkdir()
        (destination / name).write_bytes(large if name.endswith(".dat") else b"excluded journal fixture")
    originals = {}
    for path in sorted(base.rglob("*")):
        if path.is_file():
            info = path.stat()
            originals[_ordinary(path)] = {**file_receipt(path), "size": info.st_size,
                "modified_ns": info.st_mtime_ns, "created_ns": getattr(info, "st_birthtime_ns", None),
                "device": info.st_dev, "inode": info.st_ino}
    return Fixture(base, left, right, nested, session, [left, right, nested, left], originals,
                   [first, second, copy, different, alias, small, small_copy, subtitle])


def verify_sources(fixture: Fixture) -> None:
    files = {_ordinary(path): path for path in fixture.base.rglob("*") if path.is_file()}
    if files.keys() != fixture.originals.keys():
        raise ValueError("Read-only release analysis changed the source file inventory")
    for key, path in files.items():
        original = fixture.originals[key]
        info = path.stat()
        if (file_receipt(path)["sha256"] != original["sha256"]
                or info.st_size != original["size"] or info.st_mtime_ns != original["modified_ns"]
                or (info.st_dev, info.st_ino) != (original["device"], original["inode"])):
            raise ValueError("Read-only release analysis changed source bytes or identity: " + path.name)


def _relative(path: str | Path | None, fixture: Fixture) -> str | None:
    if path is None:
        return None
    relative = os.path.relpath(_ordinary(path), _ordinary(fixture.base)).replace("\\", "/")
    if relative == ".." or relative.startswith("../"):
        raise ValueError("Report contains a path outside the disposable selected fixture")
    return relative


def _roots(roots: list[Path]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    unique, aliases = [], []
    known = {}
    for path in roots:
        key = _ordinary(path)
        if key in known:
            aliases.append({"requested_path": key, "root_id": known[key]})
            continue
        root_id = f"root-{len(unique) + 1:04d}"
        known[key] = root_id
        unique.append({"root_id": root_id, "path": key, "valid": path.is_dir()})
    return unique, aliases


def _truth(fixture: Fixture, roots: list[Path], minimum: int, duplicates: bool) -> dict[str, Any]:
    selected, aliases = _roots(roots)
    inventory = {}
    root_counts = {root["root_id"]: [0, 0] for root in selected}
    for path in fixture.eligible:
        key = _ordinary(path)
        original = fixture.originals[key]
        if original["size"] < minimum:
            continue
        memberships, relative_paths = [], {}
        for root in selected:
            try:
                relative = Path(key).relative_to(root["path"])
            except ValueError:
                continue
            if root["valid"]:
                memberships.append(root["root_id"])
                relative_paths[root["root_id"]] = relative.as_posix()
                root_counts[root["root_id"]][0] += 1
                root_counts[root["root_id"]][1] += original["size"]
        if memberships:
            inventory[key] = {"root_ids": memberships, "owner_root_id": memberships[0],
                "relative_paths": relative_paths, "size": original["size"], "kind": "file",
                "extension": path.suffix.lower(), "modified_ns": str(original["modified_ns"])}
    groups = []
    if duplicates:
        physical, content = set(), {}
        for path in sorted(inventory, key=str.casefold):
            original = fixture.originals[path]
            identity = original["device"], original["inode"]
            if identity in physical:
                continue
            physical.add(identity)
            content.setdefault((original["size"], original["sha256"]), []).append(path)
        for (size, checksum), paths in content.items():
            if len(paths) > 1:
                root_ids = sorted({root for path in paths for root in inventory[path]["root_ids"]})
                groups.append({"paths": sorted(paths), "size": size, "sha256": checksum,
                    "root_ids": root_ids, "group_source_count": len(root_ids), "action_authority": False})
    return {"roots": selected, "root_counts": root_counts, "aliases": aliases,
            "files": inventory, "groups": groups, "complete": all(root["valid"] for root in selected)}


def _normalize(value: dict, fixture: Fixture, roots: list[Path], minimum: int,
               duplicates: bool, *, check_aliases: bool = True) -> tuple[dict, dict[str, int | None]]:
    truth = _truth(fixture, roots, minimum, duplicates)
    if (value.get("app_version") != VERSION or value.get("schema") != SCHEMA
            or value.get("action_authority") is not False or value.get("cancelled") is not False
            or value.get("complete") is not truth["complete"]
            or value.get("inventory_complete") is not truth["complete"]):
        raise ValueError("Frozen program returned the wrong version, authority, scope or completion state")
    expected_scope = {"recursive": True, "include_hidden": False, "exclude_patterns": ["*.skip"],
                      "min_size": minimum, "max_size": None}
    normalized_roots = []
    if len(value["roots"]) != len(truth["roots"]):
        raise ValueError("Duplicate root collapse or failed-root membership differs")
    for observed, expected in zip(value["roots"], truth["roots"]):
        count, size = truth["root_counts"][expected["root_id"]]
        if (observed["root_id"] != expected["root_id"]
                or _ordinary(observed["requested_path"]) != expected["path"]
                or observed["state"] != ("complete" if expected["valid"] else "failed")
                or observed["file_count"] != count or observed["bytes"] != size
                or observed["scan_options"] != expected_scope):
            raise ValueError("Per-root inventory, requested scope or failure state differs from fixture truth")
        actual_path = _ordinary(observed["path"]) if observed["path"] is not None else None
        if actual_path != (expected["path"] if expected["valid"] else None):
            raise ValueError(f"Canonical root identity differs: expected={expected['path']!r}; actual={actual_path!r}")
        if ((expected["valid"] and (observed["warnings"] or observed["error"] is not None))
                or (not expected["valid"] and not observed["error"])):
            raise ValueError("Per-root warning/error details do not explain the completion state")
        normalized_roots.append((observed["root_id"], _relative(observed["requested_path"], fixture),
            _relative(observed["path"], fixture), observed["state"], count, size, observed["scan_options"]))
    files, created = {}, {}
    for item in value["files"]:
        key = _ordinary(item["path"])
        if key in files:
            raise ValueError("Overlapping roots repeat a global file path")
        if not isinstance(item["modified_ns"], str) or not item["modified_ns"].lstrip("-").isdigit():
            raise ValueError("Modification timestamp lost its exact decimal-string representation")
        files[key] = {name: item[name] for name in ("root_ids", "owner_root_id", "relative_paths", "size",
                                                   "kind", "extension", "modified_ns")}
        date = item["created_ns"]
        if date is not None and (not isinstance(date, str) or not date.lstrip("-").isdigit()):
            raise ValueError("Creation timestamp is not an exact optional decimal string")
        created[key] = int(date) if date is not None else None
        known = fixture.originals.get(key, {}).get("created_ns")
        if date is not None and known is not None and int(date) != known:
            raise ValueError("Creation timestamp differs from native fixture metadata")
    if files != truth["files"]:
        raise ValueError("Frozen global inventory differs from generated metadata and scope truth")
    observed_duplicates = value["duplicates"]
    if (observed_duplicates["requested"] is not duplicates
            or observed_duplicates["complete"] is not (truth["complete"] if duplicates else None)
            or observed_duplicates["cancelled"] is not False):
        raise ValueError("Exact-analysis request/completion is inconsistent with the selected roots")
    groups = [{"paths": sorted(_ordinary(path) for path in group["paths"]),
        **{name: group[name] for name in ("size", "sha256", "root_ids", "group_source_count", "action_authority")}}
        for group in observed_duplicates["groups"]]
    order = lambda group: group["paths"]
    if sorted(groups, key=order) != sorted(truth["groups"], key=order):
        raise ValueError("Exact groups differ from byte/SHA-256/hardlink fixture truth")
    aliases = [{"requested_path": _ordinary(item["requested_path"]), "root_id": item["root_id"]}
               for item in value["duplicate_inputs"]]
    if check_aliases and aliases != truth["aliases"]:
        raise ValueError("Repeated root input did not resolve to its original membership")
    normalized_files = {_relative(path, fixture): item for path, item in files.items()}
    normalized_groups = [{**group, "paths": [_relative(path, fixture) for path in group["paths"]]} for group in groups]
    return {"roots": normalized_roots, "files": normalized_files,
            "groups": sorted(normalized_groups, key=order), "complete": truth["complete"]}, created


def normalize_report(value: dict, fixture: Fixture) -> dict:
    """Validate a full-scope GUI report against the same native byte truth.

    Registration widgets may remove a repeated folder before calling the engine;
    this does not change root membership, files, or global exact groups.
    """
    normalized, _dates = _normalize(value, fixture, fixture.roots, 0, True, check_aliases=False)
    return normalized


def _invoke(command: list[str], report: Path, engine: str, executable_sha: str) -> tuple[dict, dict]:
    stdout, stderr = report.with_suffix(".stdout.txt"), report.with_suffix(".stderr.txt")
    with stdout.open("xb") as out, stderr.open("xb") as err:
        process = subprocess.run(command, stdout=out, stderr=err, timeout=120)
    receipt = {"engine": engine, "argv": command, "exit_code": process.returncode,
               "executable_sha256": executable_sha,
               "stdout": file_receipt(stdout), "stderr": file_receipt(stderr),
               "report": file_receipt(report) if report.exists() else None}
    with report.with_suffix(".receipt.json").open("x", encoding="utf-8") as stream:
        json.dump(receipt, stream, indent=2, ensure_ascii=True)
    value = json.loads(report.read_text(encoding="utf-8-sig")) if report.exists() else {}
    return receipt, value


def run_cli_checks(commands: dict[str, list[str]], output: Path, fixture: Fixture) -> dict:
    """Run only new Windows frozen multi-root contracts and retain every output."""
    if os.name != "nt":
        raise RuntimeError("The frozen multi-root release checks require native Windows")
    if set(commands) != {"Python", "Rust"}:
        raise ValueError("Exactly the two release CLI commands are required")
    output.mkdir(parents=True, exist_ok=True)
    scenarios = [
        ("global-overlap-hardlink", fixture.roots, True, 0),
        ("inventory-only", [fixture.left, fixture.right], False, 0),
        ("offline-partial", [fixture.left, fixture.base / "offline", fixture.right], True, 0),
        ("size-filtered", [fixture.left, fixture.right], True, MIB),
    ]
    results = []
    executable_sha = {engine: file_receipt(Path(command[0]))["sha256"] for engine, command in commands.items()}
    for scenario, roots, duplicates, minimum in scenarios:
        normalized, dates, invocations = {}, {}, []
        for engine, prefix in commands.items():
            report = output / f"{scenario}-{engine}.json"
            command = [*prefix, str(roots[0])]
            for root in roots[1:]:
                command.extend(("--add-folder", str(root)))
            command.extend(("--json-multiroot", str(report), "--exclude", "*.skip", "--min-size", str(minimum)))
            if duplicates:
                command.append("--duplicates")
            receipt, value = _invoke(command, report, engine, executable_sha[engine])
            expected_exit = 0 if scenario != "offline-partial" else 2
            if receipt["exit_code"] != expected_exit or not report.exists():
                raise ValueError(f"New frozen CLI contract failed: {scenario} / {engine} / {receipt['exit_code']}")
            normalized[engine], dates[engine] = _normalize(value, fixture, roots, minimum, duplicates)
            invocations.append(receipt)
        if normalized["Python"] != normalized["Rust"]:
            raise ValueError("The two frozen programs disagree on the new multi-root semantic contract")
        comparisons = {"created_ns_compared": 0, "created_ns_availability_differences": 0,
                       "created_ns_unavailable_both": 0}
        for path, left in dates["Python"].items():
            right = dates["Rust"][path]
            if left is not None and right is not None:
                if left != right:
                    raise ValueError("Frozen programs disagree on native creation timestamps")
                comparisons["created_ns_compared"] += 1
            elif (left is None) != (right is None):
                comparisons["created_ns_availability_differences"] += 1
            else:
                comparisons["created_ns_unavailable_both"] += 1
        verify_sources(fixture)
        results.append({"scenario": scenario, "semantic_contract_matches": True,
            "inventory_files": len(normalized["Python"]["files"]),
            "exact_groups": len(normalized["Python"]["groups"]),
            "complete": normalized["Python"]["complete"], "timestamp_comparison": comparisons,
            "commands": invocations, "source_bytes_and_identity_unchanged": True})
    report = output / "negative-read-hints-Python.json"
    command = [*commands["Python"], str(fixture.session), "--duplicates", "--similar",
               "--similar-method", "name", "--name-threshold", "0.5", "--json", str(report)]
    receipt, value = _invoke(command, report, "Python", executable_sha["Python"])
    comparison = value.get("comparison_report", {})
    if (receipt["exit_code"] != 0 or value.get("app_version") != VERSION
            or value.get("duplicates") != [] or len(value.get("similar", [])) != 3
            or comparison.get("exact_results_reused") is not True
            or comparison.get("exact_difference_hints") != 3
            or comparison.get("byte_comparison_bytes") != 0
            or any(group.get("kind") != "similar_name" or group.get("evidence", {}).get("byte_identical") is not False
                   for group in value.get("similar", []))):
        raise ValueError("Frozen Python did not reuse verified different-hash hints through native Windows descriptor snapshots")
    verify_sources(fixture)
    if {engine: file_receipt(Path(command[0]))["sha256"] for engine, command in commands.items()} != executable_sha:
        raise ValueError("Frozen release executable changed during the new CLI checks")
    final = {"version": VERSION, "scope": "new native Windows frozen multi-root contracts only",
             "executable_sha256": executable_sha, "results": results,
             "reference_report": "global-overlap-hardlink-Python.json",
             "expected_inventory_files": len(_truth(fixture, fixture.roots, 0, True)["files"]),
             "expected_groups": len(_truth(fixture, fixture.roots, 0, True)["groups"]),
             "negative_read_hints": {"command": receipt, "similar_pairs": 3,
                 "exact_difference_hints": 3, "byte_comparison_bytes": 0},
             "source_bytes_and_identity_unchanged": True, "previously_passed_suites": "not rerun"}
    with (output / "CLI_V080_CHECKS.json").open("x", encoding="utf-8") as stream:
        json.dump(final, stream, indent=2, ensure_ascii=True)
        stream.write("\n")
    return final
