def _normalized(value: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", value).casefold().split())


_BY_KEY = {topic.key: topic for topic in TOPICS}
_SEARCH_TEXT = {
    topic.key: _normalized(" ".join((topic.title, topic.group, topic.summary, topic.when,
                                      *topic.steps, topic.result, topic.note,
                                      topic.technical, *topic.keywords)))
    for topic in TOPICS
}


def get_topic(key: str) -> HelpTopic | None:
    """Return a known topic, leaving fallback selection to the caller."""
    return _BY_KEY.get(key)


def topics_for_query(query: str) -> tuple[HelpTopic, ...]:
    """Match every search term while keeping the catalog's friendly order."""
    terms = _normalized(query[:512]).split()
    if not terms:
        return TOPICS
    return tuple(topic for topic in TOPICS
                 if all(term in _SEARCH_TEXT[topic.key] for term in terms))
